// Read model definitions only. No .env, credentials, or database connection.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.resolve(__dirname, '..');
const output = path.resolve(process.argv[2] || path.join(root, 'artifacts/data_dictionary_2026-10-07/schema.json'));

function printableDefault(type) {
  if (type.instance === 'ObjectId' && type.options.auto) return 'Generated ObjectId';
  const value = type.options.default;
  if (value === undefined) {
    // Mongoose arrays implicitly default to [] unless explicitly disabled.
    if (type.instance === 'Array' && !Object.prototype.hasOwnProperty.call(type.options, 'default')) return [];
    return undefined;
  }
  if (typeof value !== 'function') return value;
  if (value === Date.now) return 'Current timestamp';
  if (type.path === '_id' && type.instance === 'ObjectId') return 'Generated ObjectId';
  // Explicit schema factory defaults are pure; never execute application services.
  if (['Embedded', 'Mixed', 'Array'].includes(type.instance)) return value();
  return 'Generated by Mongoose';
}

function typeName(type) {
  if (type.schema) return type.$isMongooseDocumentArray ? 'Object[]' : 'Object';
  if (type.instance === 'Array') return `${typeName(type.caster)}[]`;
  return type.instance;
}

function fields(schema, prefix = '', nested = false) {
  return Object.entries(schema.paths).flatMap(([name, type]) => {
    const full = prefix + name;
    const options = type.options;
    const validators = type.validators.map(v => {
      if (v.type === 'user defined') {
        if (v.validator === Number.isSafeInteger) return 'Safe integer';
        return 'Custom validator (see source)';
      }
      return null;
    }).filter(Boolean);
    const row = {
      path: full, type: typeName(type), required: !!type.isRequired,
      requiredWithinParent: nested && !!type.isRequired,
      key: name === '_id' ? (nested ? 'Embedded ID' : 'PK') : '',
      generated: !nested && ['createdAt', 'updatedAt', '__v'].includes(name),
      ...(options.ref ? { ref: options.ref } : {}),
      enum: type.enumValues?.length ? type.enumValues : (type.caster?.enumValues || []),
      ...(printableDefault(type) !== undefined ? { default: printableDefault(type) } : {}),
      validators,
    };
    for (const key of ['min', 'max', 'minlength', 'maxlength', 'trim', 'uppercase', 'lowercase', 'select', 'immutable']) {
      if (options[key] !== undefined) row[key] = options[key];
    }
    return [row, ...(type.schema ? fields(type.schema, full + (type.$isMongooseDocumentArray ? '[].' : '.'), true) : [])];
  });
}

const models = fs.readdirSync(path.join(root, 'src/models')).filter(f => f.endsWith('.js')).map(file => {
  const filename = path.join(root, 'src/models', file);
  const model = require(filename);
  return {
    model: model.modelName, collection: model.collection.name, source: `src/models/${file}`,
    sourceSha256: crypto.createHash('sha256').update(fs.readFileSync(filename)).digest('hex'),
    timestamps: !!model.schema.options.timestamps,
    fields: fields(model.schema), indexes: model.schema.indexes(),
  };
});
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, JSON.stringify({ date: '2026-10-07', database: 'MongoDB / Mongoose', models }, null, 2) + '\n');
console.log(`Exported ${models.length} models, ${models.reduce((n, m) => n + m.fields.length, 0)} field paths; no database connection.`);
process.exit(0);
